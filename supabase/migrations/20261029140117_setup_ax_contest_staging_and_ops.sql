create schema if not exists ax_ops;

create table if not exists ax_ops.update_history (
  id bigint generated by default as identity primary key,
  release_id text not null unique,
  status text not null check (status in ('prepared','validated','approved','deployed','rolled_back','failed')),
  summary text not null default '',
  git_base_sha text,
  git_commit_sha text,
  db_migration text,
  backup_tag text,
  validation jsonb not null default '{}'::jsonb,
  requested_at timestamptz not null default now(),
  approved_at timestamptz,
  deployed_at timestamptz
);

create table if not exists public.stg_agents
  (like public.agents including defaults including constraints including indexes);

create table if not exists public.stg_scores
  (like public.scores including defaults including constraints including indexes);

create table if not exists public.stg_app_settings
  (like public.app_settings including defaults including constraints including indexes);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'stg_scores_agent_slot_fkey'
      and conrelid = 'public.stg_scores'::regclass
  ) then
    alter table public.stg_scores
      add constraint stg_scores_agent_slot_fkey
      foreign key (agent_slot)
      references public.stg_agents(slot)
      on delete cascade;
  end if;
end $$;

truncate table public.stg_scores;
truncate table public.stg_app_settings;
truncate table public.stg_agents cascade;

insert into public.stg_agents select * from public.agents;
insert into public.stg_scores select * from public.scores;
insert into public.stg_app_settings select * from public.app_settings;

alter table public.stg_agents enable row level security;
alter table public.stg_scores enable row level security;
alter table public.stg_app_settings enable row level security;

grant select, insert, update, delete on table
  public.stg_agents,
  public.stg_scores,
  public.stg_app_settings
to service_role;
